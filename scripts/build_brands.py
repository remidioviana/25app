"""Render the individually authored identities; never rewrite specifications or product goals.

Requires Inkscape and fontTools. Fonts retain their individual OFL notices in mobile/assets/typefaces.
"""
import json,subprocess
from pathlib import Path
from concurrent.futures import ThreadPoolExecutor
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
ROOT=Path(__file__).resolve().parents[1]
def word_paths(id,word):
 font=TTFont(ROOT/'mobile/assets/typefaces'/f'{id}.ttf');glyphs=font.getGlyphSet();cmap=font.getBestCmap();x=0;paths=[]
 for char in word:
  name=cmap.get(ord(char),'.notdef');pen=SVGPathPen(glyphs);glyphs[name].draw(pen)
  paths.append(f'<path transform="translate({x} 0)" d="{pen.getCommands()}"/>');x+=glyphs[name].width
 return ''.join(paths),x,font['head'].unitsPerEm

def main():
 brands=json.loads((ROOT/'brand-assets/brands.json').read_text());ids=json.loads((ROOT/'mobile/src/experience/identities.json').read_text());symbols=json.loads((ROOT/'brand-assets/identity-symbols.json').read_text());jobs=[]
 for b in brands:
  id=b['id'];d=ids[id];folder=ROOT/'mobile/assets/variants'/id
  inner=symbols[id].format(**dict(d,accent=d.get('signal',d['accent'])));logo=f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100">{inner}</svg>'
  (ROOT/'brand-assets/logos'/f'{id}.svg').write_text(logo+'\n');(folder/'logo.svg').write_text(logo+'\n')
  word=b['name'].replace(' AI','');paths,width,em=word_paths(id,word)
  wordmark=f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width} {em*1.4}" role="img" aria-label="{word}"><g transform="translate(0 {em}) scale(1 -1)" fill="{d["ink"]}">{paths}</g></svg>'
  (folder/'wordmark.svg').write_text(wordmark+'\n')
  for kind,w,h in [('icon',1024,1024),('splash',1284,2778),('hero',1080,1920)]:
   size=680 if kind=='icon' else 360;x=(w-size)/2;y=(h-size)/2 if kind=='icon' else h*.30
   lettering='' if kind=='icon' else f'<svg x="{w*.12}" y="{y+size+70}" width="{w*.76}" height="230" viewBox="0 0 {width} {em*1.4}"><g transform="translate(0 {em}) scale(1 -1)" fill="{d["ink"]}">{paths}</g></svg>'
   svg=f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}"><rect width="{w}" height="{h}" fill="{d["bg"]}"/><svg x="{x}" y="{y}" width="{size}" height="{size}" viewBox="0 0 100 100">{inner}</svg>{lettering}</svg>'
   source=folder/f'{kind}.svg';source.write_text(svg);jobs.append((source,folder/f'{kind}.png'))
 def render(job):
  source,target=job
  r=subprocess.run(['inkscape',str(source),'--export-type=png','--export-filename='+str(target)],capture_output=True)
  if r.returncode:raise RuntimeError('SVG render failed for '+str(source))
 with ThreadPoolExecutor(max_workers=4) as pool:list(pool.map(render,jobs))
 lines=['// Generated by scripts/build_brands.py; no specification mutation.','export const brands = '+json.dumps({b['id']:b for b in brands})+';','export const assets:Record<string,{icon:number;splash:number;hero:number;logo:string}> = {']
 for b in brands:
  id=b['id'];logo=(ROOT/'brand-assets/logos'/f'{id}.svg').read_text();lines.append(json.dumps(id)+':{icon:require("../assets/variants/'+id+'/icon.png"),splash:require("../assets/variants/'+id+'/splash.png"),hero:require("../assets/variants/'+id+'/hero.png"),logo:'+json.dumps(logo)+'},')
 lines.append('};');(ROOT/'mobile/src/brands.ts').write_text('\n'.join(lines)+'\n')
 print('Rendered 25 independent marks, outlined wordmarks and 75 native assets without changing product specifications.')
if __name__=='__main__':main()
