"""Install the approved ivory Premium 3D artwork without replacing legacy assets."""
from pathlib import Path
import hashlib
import json
import shutil
from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
BRANDS = json.loads((ROOT / 'brand-assets/brands.json').read_text())
GOLD = ROOT / 'brand-assets/gold-preview'
OUTPUT = ROOT / 'mobile/assets/variants'
registry = {}
for brand in BRANDS:
    key = brand['id']
    source = GOLD / 'mobile-first/assets' / key / 'premium-3d-ivory-1024.png'
    if key == 'adab':
        source = GOLD / 'adab-ivory-options/option-1.png'
    dest = OUTPUT / key / 'premium-ivory.png'
    im = Image.open(source).convert('RGB')
    assert im.width == im.height
    im.resize((1024, 1024), Image.Resampling.LANCZOS).save(dest, optimize=True)
    path = OUTPUT / key / 'premium-adaptive-foreground.png'
    # Adab's approved source has an opaque ivory background and has not yet
    # been independently cut out. Use its standard launcher fallback.
    if key != 'adab':
        shutil.copyfile(GOLD / 'visual-audit/production-assets' / key / 'android-foreground-432.png', path)
    registry[key] = {
        'icon': str(dest.relative_to(ROOT)),
        'sha256': hashlib.sha256(dest.read_bytes()).hexdigest(),
        'androidForeground': str(path.relative_to(ROOT)) if key != 'adab' else None,
        'background': '#F5E8D0',
    }
manifest = ROOT / 'brand-assets/premium-ivory.json'
manifest.write_text(json.dumps({'collection': 'Premium 3D Ivory', 'icons': registry}, indent=2) + '\n')
# Metro requires static asset references.
lines = ["// Generated by scripts/install-premium-identity.py.", "export const premiumIcons = {"]
for key in registry:
    lines.append(f'  "{key}": require("../../assets/variants/{key}/premium-ivory.png"),')
lines.append('};')
(ROOT / 'mobile/src/experience/premiumIcons.ts').write_text('\n'.join(lines) + '\n')
